/** 极简占位符替换：`{name}` → 变量值。 */
export function tpl(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/gu, (_, key: string) => {
    const value = vars[key]
    return value === undefined ? '' : String(value)
  })
}

